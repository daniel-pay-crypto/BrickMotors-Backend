-- ===== Usuarios =====
CREATE TABLE usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    correo          VARCHAR(255) NOT NULL UNIQUE,
    contrasena      VARCHAR(100) NOT NULL,
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    rol             VARCHAR(20)  NOT NULL DEFAULT 'CLIENTE' CHECK (rol IN ('ADMIN', 'VENDEDOR', 'CLIENTE')));

-- ===== Catálogo =====
CREATE TABLE categorias (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE productos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(20)  NOT NULL UNIQUE,
    nombre        VARCHAR(150) NOT NULL,
    descripcion   VARCHAR(500),
    precio        INT          NOT NULL CHECK (precio > 0),
    stock         INT          NOT NULL DEFAULT 0 CHECK (stock >= 0),
    descuento     INT          NOT NULL DEFAULT 0 CHECK (descuento BETWEEN 0 AND 90),
    imagen        VARCHAR(500),
    categoria_id  BIGINT       NOT NULL,
    CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id)
);

-- ===== Pedidos (Pedido N:M Producto resuelto con detalle_pedidos) =====
CREATE TABLE pedidos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL,
    fecha       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado      VARCHAR(20) NOT NULL,
    total       INT         NOT NULL CHECK (total >= 0),
    CONSTRAINT fk_pedidos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE TABLE detalle_pedidos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT       NOT NULL,
    producto_id      BIGINT       NOT NULL,
    nombre_producto  VARCHAR(150) NOT NULL,
    precio_unitario  INT          NOT NULL,
    descuento        INT          NOT NULL DEFAULT 0,
    cantidad         INT          NOT NULL CHECK (cantidad > 0),
    subtotal         INT          NOT NULL,
    CONSTRAINT fk_detalle_pedido   FOREIGN KEY (pedido_id)   REFERENCES pedidos (id) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES productos (id)
);

-- ===== Contacto =====
CREATE TABLE mensajes_contacto (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(100)  NOT NULL,
    correo   VARCHAR(255)  NOT NULL,
    mensaje  VARCHAR(1000) NOT NULL,
    fecha    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leido    BOOLEAN       NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_productos_categoria ON productos (categoria_id);
CREATE INDEX idx_pedidos_usuario     ON pedidos (usuario_id);
CREATE INDEX idx_detalle_pedido      ON detalle_pedidos (pedido_id);